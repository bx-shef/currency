<?php declare(strict_types=1);

/**
 * Какие курсы запишет модуль — правило целиком, без портала и без сети.
 *
 * ЦЕЛЬ
 *   Показать, как Main\Rates разбирает ответ НБ РБ и решает, что писать:
 *   валюты портала, коэффициент, масштаб, порог колебания.
 *
 * ГДЕ ПРИМЕНЯТЬ
 *   Объяснить заказчику, почему курс на портале такой, а не другой; прикинуть
 *   порог и коэффициент до того, как менять настройки; свой отчёт о курсах.
 *
 * ЧТО ДОЛЖНО ПОЛУЧИТЬСЯ
 *   Из настоящего ответа банка на 2026-09-29 — 30 курсов; на портале с BYN,
 *   USD, EUR, RUB пишутся три; коэффициент 1.02 поднимает курс; порог 1 %
 *   не пропускает доллар, сдвинувшийся на 0.19 %; рубль сравнивается за
 *   единицу, а не за 100.
 *
 * ЗАПУСК
 *   php examples/rates.php                                # заглушки
 *   DOCUMENT_ROOT=/var/www/portal php examples/rates.php  # живой Битрикс
 *
 *   Main\Rates ядра не зовёт, поэтому в обоих режимах результат один: ответ
 *   банка — сохранённый, из tests/fixtures/.
 */

require __DIR__.'/_bootstrap.php';

use Shef\Currency\Main\Rates;

title('Какие курсы запишет модуль');

step('1. Ответ НБ РБ');

$xml = (string)file_get_contents(dirname(__DIR__).'/tests/fixtures/nbrb-2026-09-29.xml');
$nb = Rates::parseXml($xml, '09/29/2026');

check('курсов в ответе', count($nb), 30);
check('доллар', [$nb['USD']['RATE'], $nb['USD']['SCALE']], [3.0257, 1]);
check('российский рубль — за 100', [$nb['RUB']['RATE'], $nb['RUB']['SCALE']], [3.5891, 100]);
check('ответ на другую дату — не курсы этой', Rates::parseXml($xml, '09/30/2026'), []);

step('2. Новый портал: BYN, USD, EUR, RUB, настройки по умолчанию');

$currencies = ['BYN', 'USD', 'EUR', 'RUB'];
$plan = Rates::plan($nb, $currencies, [], [], 1.0, 0, 'BYN');

foreach($plan as $row)
{
	note(sprintf('%s: %s за %d', $row['CURRENCY'], $row['RATE'], $row['RATE_CNT']));
}
check('пишутся все, кроме базовой', array_column($plan, 'CURRENCY'), ['USD', 'EUR', 'RUB']);

step('3. Коэффициент 1.02 — «на 2 % выше банка»');

$plan = Rates::plan($nb, ['USD'], [], [], 1.02, 0, 'BYN');
check('доллар', $plan[0]['RATE'], 3.0862);

step('4. Порог 1 %: вчера на портале доллар 3.02, рубль 0.0360 за 1');

$last = [
	'USD' => ['RATE' => 3.02, 'RATE_CNT' => 1],
	'RUB' => ['RATE' => 0.0360, 'RATE_CNT' => 1],
];
$plan = Rates::plan($nb, ['USD', 'RUB'], [], $last, 1.0, 1, 'BYN');

note('доллар: 3.0257 против 3.02 — 0.19 %, действует вчерашний');
note('рубль: 0.035891 за единицу против 0.0360 — 0.3 %, хотя записан за 1, а не за 100');
check('не пишется ничего', $plan, []);

done('rates');
